
/**
 * 「このページを見てよいか」を決める、たった 1 つの部品。
 *
 * 見せ方は 3 通り:
 *   public     … 誰でも見られる（名乗っていない人・ゲストも）
 *   internal   … 会社の人なら誰でも見られる（既定）
 *   restricted … 会社の人のうち、名簿に載っている人だけ
 *
 * restricted の名簿に載るのは 4 通り:
 *   ・ページを作った人（所有者）
 *   ・管理者
 *   ・個人として許可された人
 *   ・許可されたまとまりに入っている人
 *
 * **ここ以外の場所で可否を判断しない。** 入口ごとに書き比べていると、
 * 片方だけ条件が抜けて「制限したはずのページが別の入口から読める」種類の
 * 見落としが起きる（画面・素材・コメント・OGP と入口は 4 つ以上ある）。
 *
 * 判定そのもの（decideAccess）は保管庫に触らない純粋な計算にしてある。
 * 保管庫を引くのは、材料が足りないとき（restricted で、まだ可否が決まらないとき）の 1 回だけ。
 *
 * 中身は 3 つに分けてある。述語（access-rules）・入口の関門（access-gates）・
 * 名簿と共有の操作（access-roster）。呼ぶ側はこれまでどおりここから読み込む。
 */
