/**
 * 動きの正本（DESIGN.md 12 章）。画面・道具箱・ログインの 1 枚が、ここの数字だけで動く。
 *
 * 決まりは 3 つ。
 *   1. 押した結果は返事を待たずにその場で映す（楽観）。待っている間に部品を薄くしない。
 *   2. 動かすのは透明度・位置（transform）・色だけ。幅や高さや余白を動かさない（描き直しが要り、引っかかる）。
 *   3. 長さとカーブはここから取る。数字の直書きは `tests/checks/check-ui-motion.mjs` が落とす。
 *
 * 同じ数字を `src/app/globals.css` の `--ws-motion-*` / `--ws-ease*` にも書いてある（CSS はここを読めない）。
 * 食い違いは同じ検査が見る。
 */
export const MOTION = {
  /** 指を乗せた・離したときの色の変化。これより長いと指に遅れて見える */
  quick: 120,
  /** 状態が変わるとき（選んだ・開いた）。出だしが速く、終わりで減速する */
  base: 200,
  /** 閉じる・消える。出すときより速く（消えるものを見せ続けない） */
  exit: 100,
  /** 横に送るとき（覗き見のカード・下から出る板） */
  swipe: 340,
  /** 「待っている」と見せ始めるまでの間。これより早く届く応答には何も出さない */
  wait: 400,
} as const;

/** 出だしが速く、終わりで減速する（iOS の標準の動きに近い）。入る・変わる・消えるの全部に使う */
export const EASE = "cubic-bezier(0.2, 0, 0, 1)";

/** 横に送るときの減速。長い尾を引いて吸い付く（行きすぎて戻る跳ね返りは付けない） */
export const EASE_SWIPE = "cubic-bezier(0.32, 0.72, 0, 1)";
