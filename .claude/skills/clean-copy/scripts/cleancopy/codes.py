# -*- coding: utf-8 -*-
"""判定コードの正本。

清書の機械が出す合図は、ここに書いてある分だけ。手引きにも同じ表を書き写さない
（写した瞬間に、どちらかが古くなる）。手引きからはこのファイルを名指しで指す。

段は 3 つだけ。

  error   … 投稿しない。既定案を添えて人に聞く。了承をもらってから、作業ファイルにだけ既定を当てる
  fixable … 聞かずに作業ファイルだけ直す（原本は触らない）
  warn    … 直さない。変換は続け、完了報告に書く

**言葉・数字・順番を変える直しは 1 つも置かない。** 誤字（「こんんちは」）はそのまま出る。
直してよいのは「入れ物」（見出しの深さ・表のマスの数・囲みの閉じ）だけで、
それも作業ファイルの上での話。
"""

ERROR = "error"
FIXABLE = "fixable"
WARN = "warn"

# code -> (段, 何が起きているか, 既定でどうするか)
# 既定（3 つ目）が空文字なのは「機械には直しようがない」もの。
CATALOG = {
    # ---- error（止まる）--------------------------------------------------
    "EMPTY_SOURCE": (
        ERROR,
        "原本が空（文字が 1 つも無い）",
        "",
    ),
    "UNREADABLE": (
        ERROR,
        "原本が読めない（ファイルが無い・文字の並びが壊れている）",
        "",
    ),
    "UNCLOSED_FENCE": (
        ERROR,
        "コードの囲み（``` か ~~~）が閉じていない",
        "末尾で閉じたことにして出す",
    ),
    "TABLE_HEADER_SEP_MISMATCH": (
        ERROR,
        "表の見出し行と区切り行で、マスの数が違う",
        "多いほうに合わせて、足りないマスを空で埋める（言葉は落とさない）",
    ),
    "TABLE_ROW_EXTRA": (
        ERROR,
        "表の本文行のマスが、見出し行より多い",
        "列を増やして、余った言葉をそのまま残す（落とさない）",
    ),
    "NO_HEADING_SHORT": (
        ERROR,
        "見出しが 1 つも無く、2000 字に届かない",
        "ファイル名（拡張子なし）を表題として先頭に立てる",
    ),
    # ---- fixable（作業ファイルだけ直す）----------------------------------
    "HEADING_SKIP": (
        FIXABLE,
        "見出しの段が飛んでいる（# の次が ### など）",
        "深い側を 1 段ずつ浅くして、飛びを無くす（語は変えない）",
    ),
    "TABLE_ROW_SHORT": (
        FIXABLE,
        "表の本文行のマスが、見出し行より少ない",
        "空のマスを足して数を合わせる",
    ),
    # ---- warn（直さず報告）-----------------------------------------------
    "RAW_STYLE": (
        WARN,
        "原本に <style> が書かれている",
        "",
    ),
    "RAW_SCRIPT": (
        WARN,
        "原本に <script> が書かれている",
        "",
    ),
    "RAW_EXTERNAL": (
        WARN,
        "原本に、外から読み込む指定がある（link・iframe・外部の img など）",
        "",
    ),
    "RAW_COLOR": (
        WARN,
        "原本の生 HTML に色が焼き込まれている（style の色指定・生の色名クラス）",
        "",
    ),
    "NO_HEADING_LONG": (
        WARN,
        "見出しが 1 つも無く、2000 字以上ある",
        "先頭の空でない 1 行を、そのまま表題にする（作文しない）",
    ),
    "IMAGE_MISSING": (
        WARN,
        "貼ってある絵が、原本と同じフォルダに見つからない",
        "",
    ),
    "HEADING_FLATTEN": (
        WARN,
        "##### より深い見出しがある",
        "h4 に潰して出す（目盛りの外に段を作らない）",
    ),
}

#: 変換のときに `<style>` `<script>` と一緒に落とすタグ（外から物を取ってくるもの）。
#: `<a href="https://...">` は「読みに行く先」であって読み込みではないので、ここに入れない。
EXTERNAL_TAGS = ("link", "iframe", "img", "source", "embed", "object", "video", "audio", "track")

#: 見出しが無い原本を「短い」と「長い」に分ける境目。
#: 手引きの「2,000 字以上あって見出しが 1 つも無いときだけ、原本の文言を抜いて見出しに立てる」に合わせる。
NO_HEADING_LONG_THRESHOLD = 2000


def severity(code):
    """判定コードの段を返す。知らないコードは error 扱い（黙って通さない）。"""
    return CATALOG.get(code, (ERROR, "", ""))[0]


def describe(code):
    """判定コードの説明を返す。"""
    return CATALOG.get(code, (ERROR, code, ""))[1]


def default_action(code):
    """既定でどう直すかを返す。直しようが無いものは空文字。"""
    return CATALOG.get(code, (ERROR, "", ""))[2]
