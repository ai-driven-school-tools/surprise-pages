-- 版の目印は「保管庫ぜんぶで 1 つ」ではなく「そのページの中で 1 つ」にする。
--
-- 0004 では目印を保管庫ぜんぶで 1 つに縛っていた。これが git の性質とぶつかる。
-- git のコミットの番号は**コミット 1 つに 1 個**で、ページ 1 枚に 1 個ではない。
-- 1 回のコミットで 2 枚のページを直していれば、その 2 枚は同じ番号を持つ。
-- 過去の版を git から移すときに、2 枚目が必ず弾かれてしまう。
--
-- 縛りを緩めても困らない。本文を引く処理は、どこも必ずページを指定してから
-- 目印で引いている（目印だけで引く道はコードのどこにも無い）。
-- これから積む版の目印は「親の目印 + 呼び名 + 中身」から計算するので、
-- ページが違えば材料が違い、結果として重ならない。
--
-- 縛りを外すのではなく「ページごと」に付け替える。同じページに同じ目印が
-- 2 つ入ると、どちらの本文が正なのか決められなくなるため。

alter table public.page_revisions
  drop constraint page_revisions_version_id_key;

alter table public.page_revisions
  add constraint page_revisions_page_id_version_id_key unique (page_id, version_id);

comment on column public.page_revisions.version_id is
  '版の目印。sha256(親の目印 + 呼び名 + 版番号 + 書いた人 + 時刻 + 本文) の先頭 40 桁。'
  '移行した版は当時の git のコミット番号そのもの。'
  '同じページの中では重ならないが、ページをまたぐと重なることがある'
  '（1 回のコミットで 2 枚のページを直していた場合）';
