-- ページの「作った人」を複数にできるようにする（共同の作った人）。
--
-- いまは作った人が 1 人だけ（pages.created_by）で、その人が休むとページが孤児になる。
-- 共有の設定を触れるのが本人と管理者しかいないので、誰も許可を足せない・外せない。
--
-- 増やすのは表 1 つでも行の種類でもなく、**いまある許可の行に「役割」の列を 1 つ**。
-- 共同の作った人も「許可の行」の一種として持つ。こうすると:
--   見られること … いまの判定（page_access_facts / lib/access.ts）がそのまま面倒を見る。
--                  owner の行も許可の行なので、可否の側は 1 行も変えなくてよい
--   増える判定  … 「共有を触れるか」の 1 つだけ
--
-- 消す印（deleted_at）は置かない。トリガも要らない。
-- 0 人になって困る名簿ではないため。最後の共同の作った人が外れても、
-- 帳簿上の作った人（pages.created_by）と管理者（admins）が必ず残り、ページは開ける。
-- 0 人を数えて止める番人（0007 の admins）が要ったのは、あちらが 0 人になると
-- 誰も助けられなくなる名簿だったから。ここは違う。

-- ---------------------------------------------------------------------------
-- 1. 役割の列
-- ---------------------------------------------------------------------------
-- 既定は 'viewer'。既にある行は全部 viewer になり、意味は今までと同じ（見てよいだけ）。
alter table public.page_permissions
  add column role text not null default 'viewer'
  check (role in ('viewer', 'owner'));

comment on column public.page_permissions.role is
  '役割。viewer = 見てよいだけ / owner = 共同の作った人（共有の設定も触れる）。'
  '既定は viewer。owner を名乗れるのは個人あての行だけ（page_permissions_owner_is_member）';

-- ---------------------------------------------------------------------------
-- 2. owner は個人あての行だけ
-- ---------------------------------------------------------------------------
-- 「誰が共有を触れるか」の答えに人の集合（まとまり）が混ざると、責任の所在が濁る。
-- まとまりに owner を出せてしまうと、
--   ・あとからまとまりに入った人が、黙って共有を触れる側になる
--   ・そのまとまりを消したとき、誰が触れなくなったのかを追えない
-- 入口（画面・API）の心がけに任せず、表の側で塞ぐ。
alter table public.page_permissions
  add constraint page_permissions_owner_is_member
  check (role <> 'owner' or grantee_kind = 'member');

comment on constraint page_permissions_owner_is_member on public.page_permissions is
  'owner はまとまりに出せない。共有を触れる相手は必ず個人 1 人に定まるようにする';

-- ---------------------------------------------------------------------------
-- 3. 帳簿上の作った人は動かさない
-- ---------------------------------------------------------------------------
-- ここで共同の作った人を足しても、pages.created_by は書き換えない。
-- あちらは「最初の版を書いた人」という履歴（帰属）で、いま誰が触れるかとは別のもの。
-- 上書きすると、誰が持ち込んだページなのかを二度と辿れなくなる。
-- 「いま共有を触れる人」を知りたい側は、created_by と role='owner' の行の両方を見る。
--
-- 0004 の説明から「（所有者）」だけ落とす。所有者が 1 人に定まる前提が消えたため、
-- あのままだと「作った人 = 唯一の所有者」と読めてしまう。列の中身と型は変えない。
comment on column public.pages.created_by is
  '最初の版を書いた人のメールアドレス。履歴なので動かさない。'
  '共同の作った人はここではなく page_permissions.role = ''owner'' で足す';
