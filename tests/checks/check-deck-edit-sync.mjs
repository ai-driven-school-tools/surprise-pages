import { build } from 'esbuild';
import { root, dir } from './paths.mjs';
await build({entryPoints:[`${root}/src/widget/deck/edit/sync.ts`],outfile:`${dir}/deck-edit-sync.mjs`,bundle:true,platform:'node',format:'esm'});
const { DeckEditQueue } = await import(`${dir}/deck-edit-sync.mjs`);
let fails=0;
function ok(label,value){ console.log(`${value?'OK  ':'NG  '}${label}`); if(!value) fails++; }
const op = (value)=>({value});
const mergedUndo=new DeckEditQueue('v1');mergedUndo.enqueue([op('edit')],'sent',false,[op('optimistic inverse')]);mergedUndo.next();mergedUndo.undo('undo');mergedUndo.acknowledge('v2',[op('server inverse retaining others')]);
ok('保存中の取り消しは受領した逆操作で他者の変更を残す',mergedUndo.next().operations[0].value==='server inverse retaining others');
const emptyUndo=new DeckEditQueue('v1');emptyUndo.enqueue([op('edit')],'sent',false,[op('inverse')]);emptyUndo.next();emptyUndo.undo('undo');emptyUndo.acknowledge('v2',[]);
ok('実際には変更がなかった保存へ空の取り消しを送らない',!emptyUndo.dirty);
const redundant=new DeckEditQueue('v1');redundant.enqueue([op('already applied')],'redundant');redundant.next();redundant.acknowledge('v2',[]);
ok('別の人が同じ結果へ直していた操作を空の取り消しにしない',!redundant.canUndo);
const typingBurst=new DeckEditQueue('v1');
typingBurst.enqueue([op('a')],'typing-a',true);typingBurst.enqueue([op('b')],'typing-b',true);
ok('未送信の連続入力はひとかたまりで保存する',typingBurst.next().operations.length===2);
typingBurst.enqueue([op('c')],'typing-c',true);typingBurst.enqueue([op('d')],'typing-d',true);
typingBurst.failed('network');
ok('入力をまとめても送信済み操作の中身は変えない',typingBurst.next().operations.map(x=>x.value).join('')==='ab');
typingBurst.acknowledge('v2',[]);
ok('送信中の追加入力は次のまとまりへ残す',typingBurst.next().operations.map(x=>x.value).join('')==='cd');
const queue = new DeckEditQueue('v1');
queue.enqueue([op('A')],'batch-a');
const first=queue.next();
queue.enqueue([op('B')],'batch-b');
ok('保存中の操作を重ねて送らない',queue.next()===null);
queue.failed('network');
ok('再送の識別子と本文を変えない',JSON.stringify(queue.next())===JSON.stringify(first));
queue.acknowledge('v2',[op('undo-a')]);
ok('保存中に追加した操作を残す',queue.pendingOperations()[0].value==='B');
ok('次の操作は保存された版を土台にする',queue.next().baseVersionId==='v2');
queue.acknowledge('v3',[op('undo-b')]);
ok('自分の直前の操作だけ取り消す',queue.undo('undo-batch') && queue.next().operations[0].value==='undo-b');
queue.acknowledge('v4',[op('B')]);
ok('取り消しをやり直せる',queue.redo('redo-batch') && queue.next().operations[0].value==='B');
queue.failed('conflict');
ok('競合後に勝手に上書きを続けない',queue.next()===null && queue.pendingOperations().length===1);
const draft=queue.exportDraft(100);
const restored=DeckEditQueue.restore(draft,200);
ok('競合した下書きは復元後も止まる',restored!==null && restored.next()===null);
ok('3日を過ぎた下書きは捨てる',DeckEditQueue.restore(draft,100+3*86400000)===null);
const lostAck=new DeckEditQueue('v1');lostAck.enqueue([op('A')],'same-id');lostAck.next();
const reboot=DeckEditQueue.restore(lostAck.exportDraft(100),101);
ok('応答を失った保存は再起動後も同じ識別子で再送する',reboot.next().operationId==='same-id');
const bounded=new DeckEditQueue('v1');bounded.enqueue([op('A')],'bounded');
for(let i=0;i<5;i++){bounded.next();bounded.failed('network');}
ok('通信の再試行に上限がある',bounded.next()===null && bounded.status==='paused');
bounded.retry();ok('利用者が再試行すれば同じ操作を再送する',bounded.next().operationId==='bounded');
const remote=new DeckEditQueue('v1');remote.enqueue([op('A')],'a');
ok('送信前の遠隔更新は次の操作の土台になる',remote.advance('v2') && remote.next().baseVersionId==='v2');
ok('送信中の遠隔更新は順序を崩さず延期する',!remote.advance('v3'));
const branch=new DeckEditQueue('v1');branch.enqueue([op('A')],'a');branch.next();branch.acknowledge('v2',[op('undo-a')]);branch.undo('u');branch.next();branch.enqueue([op('B')],'b');branch.acknowledge('v3',[op('A')]);branch.next();branch.acknowledge('v4',[op('undo-b')]);
ok('取り消しの保存中に別の編集をしたら古いやり直しを残さない',!branch.canRedo);
await build({entryPoints:[`${root}/src/lib/deck/edit/source.ts`],outfile:`${dir}/deck-edit-sync-source.mjs`,bundle:true,platform:'node',format:'esm'});
