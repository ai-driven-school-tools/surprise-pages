import { build } from "esbuild";
import { readFile, writeFile, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../../", import.meta.url));
const built = await build({ entryPoints: [`${root}src/deck-design/runtime.ts`], bundle: true, minify: true, write: false, format: "iife", platform: "browser", target: "es2020" });
const css = await readFile(`${root}src/deck-design/styles.css`, "utf8");
const formatsCss = await readFile(`${root}src/deck-design/formats.css`, "utf8");
const js = built.outputFiles[0].text.replace(/<\/script/gi, "<\\/script").replace(/[ \t]+$/gm, "");
const presetBundle = await build({ entryPoints: [`${root}src/lib/deck/design/design.ts`], bundle: true, write: false, format: "esm", platform: "node" });
const { DECK_PRESETS, DECK_DIAGONAL_MARK, DECK_SCHOOL_MARK } = await import(`data:text/javascript;base64,${Buffer.from(presetBundle.outputFiles[0].text).toString("base64")}`);
const html = `<!-- Generated by scripts/build/deck-design.mjs. Shared layout and appearance; embed unchanged. -->\n<style data-deck-design-style="3" ${DECK_DIAGONAL_MARK} ${DECK_SCHOOL_MARK}>\n${css}\n${formatsCss}</style>\n<script data-deck-design-runtime="3" data-deck-logo-layouts ${DECK_DIAGONAL_MARK} ${DECK_SCHOOL_MARK}>${js}</script>\n<script defer src="https://cdn.jsdelivr.net/npm/echarts@6.1.0/dist/echarts.min.js" data-deck-companion="echarts-6.1.0"></script>\n`;
const presetJson = JSON.stringify({ version: 1, styles: DECK_PRESETS }, null, 2) + "\n";
if (process.argv.includes("--check")) {
  if (await readFile(`${root}src/templates/deck-styles.json`, "utf8") !== presetJson) throw new Error("完成スタイルの配布用設定を組み立て直してください");
} else await writeFile(`${root}src/templates/deck-styles.json`, presetJson);
let deckRuntime = await readFile(`${root}src/templates/deck.html`, "utf8");
const media = await build({stdin:{contents:'import {installDeckYouTube} from "./src/lib/deck/media/youtube";installDeckYouTube(document);',resolveDir:root},bundle:true,minify:true,write:false,format:"iife",platform:"browser",target:"es2020"});
const withMedia=deckRuntime.replace(/\/\* DECK_MEDIA_START \*\/[\s\S]*?\/\* DECK_MEDIA_END \*\//,()=>`/* DECK_MEDIA_START */\n${media.outputFiles[0].text.replace(/<\/script/gi,"<\\/script")}/* DECK_MEDIA_END */`);
if(process.argv.includes("--check")){if(withMedia!==deckRuntime)throw new Error("動画の再生部品を組み立て直してください");}
else if(withMedia!==deckRuntime)await writeFile(`${root}src/templates/deck.html`,withMedia);
deckRuntime=withMedia;
const runtimeBody = deckRuntime.slice(deckRuntime.indexOf("-->") + 3);
const runtimeStyle = runtimeBody.match(/<style>[\s\S]*?<\/style>/)?.[0];
const runtimeScript = runtimeBody.match(/<script>[\s\S]*?<\/script>/)?.[0];
if (!runtimeStyle || !runtimeScript) throw new Error("スライドの操作部品が見つかりません");
const previewModule = `// Generated by scripts/build/deck-design.mjs; reviewed stock runtimes.\nexport const navigationRuntime = ${JSON.stringify(runtimeScript)};\nexport const designStyle = ${JSON.stringify(`<style data-deck-design-style="3" ${DECK_DIAGONAL_MARK} ${DECK_SCHOOL_MARK}>\n${css}\n${formatsCss}</style>`)};\nexport const designRuntime = ${JSON.stringify(`<script data-deck-design-runtime="3" data-deck-logo-layouts ${DECK_DIAGONAL_MARK} ${DECK_SCHOOL_MARK}>${js}</script>`)};\n`;
if (process.argv.includes("--check")) {
  if (await readFile(`${root}src/lib/deck/preview.generated.ts`, "utf8") !== previewModule) throw new Error("編集用の共通部品を組み立て直してください");
} else await writeFile(`${root}src/lib/deck/preview.generated.ts`, previewModule);
if (process.argv.includes("--check")) {
  if (await readFile(`${root}src/templates/deck-design.html`, "utf8") !== html) throw new Error("スライドの共通部品を組み立て直してください");
} else await writeFile(`${root}src/templates/deck-design.html`, html);

const validator = await build({ entryPoints: [`${root}scripts/build/deck-design-check.ts`], bundle: true, minify: true, write: false, format: "esm", platform: "node", target: "node20" });
const checker = validator.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (await readFile(`${root}bin/deck-design-check.mjs`, "utf8") !== checker) throw new Error("スライドの検査を組み立て直してください");
} else {
  await writeFile(`${root}bin/deck-design-check.mjs`, checker);
  const examples = `${root}tests/checks/fixtures/internal/example`;
  for (const name of await readdir(examples)) {
    if (!name.startsWith("deck") || !name.endsWith(".html")) continue;
    const current = await readFile(`${examples}/${name}`, "utf8");
    let next = current;
    if (name.startsWith("deck-design-")) next = next.replace(/<!--DECK_DESIGN_START-->[\s\S]*?<!--DECK_DESIGN_END-->/, () => `<!--DECK_DESIGN_START-->\n${html}<!--DECK_DESIGN_END-->`);
    // The base navigation is also embedded. Keep every checked example on the
    // same source so a control change cannot leave a stale, apparently working copy.
    // Match only tags that start a line. The template comment mentions "<style>"
    // as text ("下の <style>"), and treating that as a tag would swallow the
    // comment and hide the real stylesheet inside it.
    next = next.replace(/^[ \t]*<style>[\s\S]*?<\/style>/gm, block => block.includes("--deck-k") && block.includes("data-deck-frame") ? runtimeStyle : block);
    next = next.replace(/^[ \t]*<script>[\s\S]*?<\/script>/gm, block => block.includes("var WIDTH = 1280;") && block.includes("data-deck-ready") ? runtimeScript : block);
    if (name.startsWith("deck-design-")) {
      const kit = next.match(/<!--DECK_DESIGN_START-->[\s\S]*?<!--DECK_DESIGN_END-->/)?.[0];
      if (kit && next.indexOf(kit) > next.indexOf("</head>")) {
        next = next.replace(kit, "").replace(runtimeStyle, "").replace(runtimeScript, "");
        next = next.replace("</head>", () => `${kit}\n${runtimeStyle}\n${runtimeScript}\n</head>`);
      }
    }
    if (current !== next) await writeFile(`${examples}/${name}`, next);
  }
}
