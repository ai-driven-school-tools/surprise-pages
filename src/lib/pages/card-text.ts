/**
 * 共有カードの絵に載せる字を、**実際に描ける形**へ寄せる。
 *
 * ## なぜ要るか（豆腐が出る）
 *
 * 絵を作る道具（next/og）は、束ねてある書体に無い字を見つけると、その字だけを
 * 外から取り寄せて描く。日本語はこれで出る。ところが**記号は取り寄せられないものがある**。
 * 取り寄せに失敗した字は「□」（豆腐）になり、しかも**何も知らせず**そうなる。
 *
 * 厄介なのは、同じ字でも前後の言葉で結果が変わること。日本語と混ざっていると、
 * 記号も日本語の書体から探しに行くので、単独なら出た罫線が豆腐になる。だから
 * 「試したら出た」では足りず、**日本語に混ぜて**試す必要がある。
 *
 * ## この表の出どころ
 *
 * 下の対応は、日本語に混ぜて 1 字ずつ実際に描かせて選んだもの。左側が豆腐になった字で、
 * 右側は同じ試し方で出た字だけを充てている。**思いつきで足さないこと**——足すときは
 * 同じやり方で確かめる（`日本語○日本語` を描いて □ にならないかを見る）。
 *
 *   出なかった: ─ ━ ┃ │ ｜ ⇒ ✓ ✕ ◆ ★ ☆ ～ Ⅰ ℃ ㎡
 *   出た      : — ― – ‐ | / ・ ※ ● ○ ▲ ▼ → ← ↑ ↓ 〜 ✔ ✖ × ① № € ‼ ⚠
 *
 * ## 直す側の言い分
 *
 * 題名を勝手に書き替えるのは本来避けたいが、カードの絵は**すでに切り落としている**
 * （長い題は末尾を「…」にする）ので、絵の中の字は本文の写しではない。読める記号に
 * 寄せるほうが、□ が並ぶより読み手に正しく伝わる。**ページ本体の題名には触らない**
 * ——ここが効くのは絵の中だけ。
 */

/**
 * 罫線の連なり。`──` のように 2 つ以上並べて区切りに使われることが多いので、
 * 連なりごと 1 本のダッシュにする（1 つずつ替えると `——` になって間延びする）。
 */
const RULES: readonly (readonly [RegExp, string])[] = [
  [/[\u2500-\u2501\u2504-\u2505\u2508-\u2509\u254c-\u254d]+/g, "—"],
  [/[\u2502\u2503\u2506\u2507\u250a\u250b\uff5c]/g, "|"],
  // 全角チルダ（Windows の「〜」）。波ダッシュは出るので、そちらへ寄せる
  [/\uff5e/g, "\u301c"],
  [/\u21d2/g, "\u2192"],
  [/\u2713/g, "\u2714"],
  [/\u2715/g, "\u2716"],
  // 飾りの星と菱形。充てる相手がいないので落とし、空いた間を詰める
  [/[\u2605\u2606\u25c6]/g, ""],
];

/** 記号を落としたあとに残る二重の空白を、1 つに詰める。 */
const GAPS = /[ \u3000]{2,}/g;

export function drawableText(value: string): string {
  let out = value;
  for (const [pattern, replacement] of RULES) out = out.replace(pattern, replacement);
  return out.replace(GAPS, " ").trim();
}
