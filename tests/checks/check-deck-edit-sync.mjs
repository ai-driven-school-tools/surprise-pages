const original=prepareDeckEdit('<!doctype html><html><body data-deck><main data-deck-slides><section data-deck-slide><p>Hello</p><p>World</p></section></main></body></html>');
const paragraphs=original.nodes.filter(node=>node.tag==='p');
const mine={kind:'text',target:paragraphs[0].id,run:0,before:'Hello',after:'Hello A'};
const theirs={kind:'text',target:paragraphs[1].id,run:0,before:'World',after:'World B'};
const collaboration=new DeckEditQueue('v1');collaboration.enqueue([mine],'mine');
const latest=applyDeckEditOperations(original.html,[theirs]);collaboration.advance('v2');collaboration.next();
const merged=applyDeckEditOperations(latest.html,collaboration.pendingOperations());collaboration.acknowledge('v3',merged.inverse);
ok('共同編集の正本へ自分の未送信操作を重ねても他人の文章を残す',merged.html.includes('Hello A')&&merged.html.includes('World B'));
collaboration.undo('undo-mine');const undoMine=collaboration.next();
const undone=applyDeckEditOperations(merged.html,undoMine.operations);
ok('取り消しでも他人の変更は戻さない',undone.html.includes('>Hello<')&&undone.html.includes('World B'));
const typing=new DeckEditQueue('v1');typing.enqueue([mine],'first');typing.next();
typing.enqueue([{...mine,before:'Hello A',after:'Hello AB'}],'second');
const acknowledged=applyDeckEditOperations(original.html,[mine,theirs]);typing.acknowledge('v2',acknowledged.inverse.slice(1));
const continued=applyDeckEditOperations(acknowledged.html,typing.pendingOperations());
ok('保存応答を待ちながら続けた入力を最新の正本に残す',inspectDeckEdit(continued.html).nodes.find(node=>node.id===paragraphs[0].id).textRuns[0].text==='Hello AB');
const structural=prepareDeckEdit('<html><head><style>.red{color:red}</style></head><body data-deck><main data-deck-slides><section data-deck-slide><p class="red">Title</p><img src="one.png"></section></main></body></html>');
const fingerprint=deckEditStructureFingerprint(structural.html);
ok('配色の設定変更を通常の文字更新として扱わない',fingerprint!==deckEditStructureFingerprint(structural.html.replace('color:red','color:blue')));
ok('既存要素のクラス変更を見逃さない',fingerprint!==deckEditStructureFingerprint(structural.html.replace('class="red"','class="blue"')));
const textTarget=structural.nodes.find(node=>node.tag==='p').id;
const ordinary=applyDeckEditOperations(structural.html,[{kind:'text',target:textTarget,run:0,before:'Title',after:'New title'},{kind:'style',target:textTarget,property:'translate',before:null,after:'1px 2px'}]);
ok('通常の共同入力と移動では元の描画を作り直さない',fingerprint===deckEditStructureFingerprint(ordinary.html));
